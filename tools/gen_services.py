"""Writes services.yaml and the English service texts from actions.ACTIONS.

Needs Home Assistant, e.g.:
  docker run --rm -v "$PWD:/w" -w /w --entrypoint python3 \
    ghcr.io/home-assistant/home-assistant:2026.10.2 tools/gen_services.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), "/usr/src/homeassistant"]

import homeassistant  # noqa: E402, F401  (aliases voluptuous)
import voluptuous as vol  # noqa: E402

from custom_components.monsieur_cuisine.actions import ACTIONS  # noqa: E402

COMPONENT = ROOT / "custom_components" / "monsieur_cuisine"


def selector(validator):
    while isinstance(validator, vol.All):
        validator = validator.validators[0]
    if isinstance(validator, vol.In):
        return {"select": {"options": list(validator.container)}}
    if isinstance(validator, vol.Coerce):
        return {int: {"number": {"min": 0, "max": 999999999, "mode": "box"}},
                bool: {"boolean": None}, str: {"text": None}}[validator.type]
    if isinstance(validator, list) or validator is dict:
        return {"object": None}
    return {"text": None}


def main() -> None:
    spec, texts = {}, {}
    for action in ACTIONS:
        fields = {}
        texts[action.name] = {"name": action.title, "description": action.description}
        for marker, validator in {**action.schema, **(action.admin_schema or {})}.items():
            key = marker.schema
            field = {"selector": selector(validator)}
            if isinstance(marker, vol.Required):
                field["required"] = True
            fields[key] = field
            texts[action.name].setdefault("fields", {})[key] = {
                "name": key.replace("_", " ").capitalize(), "description": marker.description}
        spec[action.name] = {"fields": fields} if fields else None
    import yaml
    (COMPONENT / "services.yaml").write_text(
        "# Generated by tools/gen_services.py\n" + yaml.safe_dump(spec, sort_keys=False).replace(": null", ":"))
    for name in ("strings.json", "translations/en.json"):
        path = COMPONENT / name
        data = json.loads(path.read_text())
        data["services"] = texts
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


main()
